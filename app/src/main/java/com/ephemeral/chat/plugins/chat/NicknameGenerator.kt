package com.ephemeral.chat.plugins.chat

import kotlin.random.Random

/**
 * 随机用户名生成器。
 * 格式：形容词 + 动物 + 编号（如"飞行的企鹅42"）
 * 50 形容词 × 50 动物 × 90 编号 = 225,000 种组合
 */
object NicknameGenerator {

    private val adjectives = listOf(
        "飞行的", "沉默的", "迷路的", "好奇的", "慵懒的", "快乐的", "勇敢的", "害羞的",
        "神秘的", "温柔的", "活泼的", "安静的", "笨拙的", "优雅的", "调皮的", "严肃的",
        "浪漫的", "冷酷的", "热情的", "忧郁的", "机智的", "呆萌的", "潇洒的", "固执的",
        "随和的", "挑剔的", "慷慨的", "吝啬的", "健谈的", "寡言的", "乐观的", "悲观的",
        "谨慎的", "冒失的", "沉稳的", "浮躁的", "勤奋的", "慵懒的", "聪慧的", "憨厚的",
        "狡猾的", "天真的", "成熟的", "稚嫩的", "威武的", "娇小的", "蓬松的", "灵动的",
        "笨重的", "慵懒的",
    )

    private val animals = listOf(
        "企鹅", "狐狸", "海鸥", "考拉", "萤火虫",
        "刺猬", "水母", "章鱼", "蝴蝶", "松鼠",
        "海豚", "熊猫", "老虎", "兔子", "猫咪",
        "柴犬", "海龟", "猫头鹰", "鲸鱼", "蚂蚁",
        "蜜蜂", "蜗牛", "蝙蝠", "浣熊", "袋鼠",
        "树懒", "梅花鹿", "灰狼", "棕熊", "雄鹰",
        "燕子", "麻雀", "乌鸦", "鹦鹉", "金鱼",
        "螃蟹", "龙虾", "青蛙", "壁虎", "变色龙",
        "鳄鱼", "斑马", "长颈鹿", "河马", "犀牛",
        "海象", "海豹", "北极熊", "孔雀", "丹顶鹤",
    )

    /**
     * 生成随机用户名。
     * @return 形容词+动物+编号（10-99）
     */
    fun generate(): String {
        val adj = adjectives[Random.nextInt(adjectives.size)]
        val animal = animals[Random.nextInt(animals.size)]
        val number = Random.nextInt(10, 100)
        return "$adj$animal$number"
    }
}
